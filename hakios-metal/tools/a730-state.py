#!/usr/bin/env python3
"""Extract A730 magic-register facts from Mesa, without executing its Python.

Usage: a730-state.py freedreno_devices.py MESA_GEN_DIR [--check]
"""
import ast
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parents[1]
tree = ast.parse(pathlib.Path(sys.argv[1]).read_text())
registers = {}
for line in (pathlib.Path(sys.argv[2]) / 'a6xx.xml.h').read_text().splitlines():
    m = re.match(r'#define (REG_\w+)\s+(0x[\da-f]+)\s*$', line)
    if m:
        registers[m[1]] = int(m[2], 16)


def address(node):
    if isinstance(node, ast.Attribute):
        return registers[node.attr]
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return address(node.left) + ast.literal_eval(node.right)
    raise ValueError(ast.dump(node))


values = {node.targets[0].id: node.value for node in tree.body if isinstance(node, ast.Assign)
          and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name)}
lines = ['// A730 facts from Mesa 25.0.7 freedreno_devices.py; generated by tools/a730-state.py.\n']
# Raw state precedes named state in tu6_init_static_regs. The _blit entry is
# another value for RB_DBG_ECO_CNTL (also zero), not another register.
for pair in values['a730_raw_magic_regs'].elts:
    reg, val = pair.elts
    lines.append(f'GPU_MAGIC({address(reg):#06x}, {ast.literal_eval(val):#010x}) // {ast.unparse(reg)}\n')
for item in values['a730_magic_regs'].keywords:
    if item.arg.endswith('_blit'):
        continue
    name = 'REG_A6XX_' + item.arg
    reg = registers.get(name, registers.get('REG_A7XX_' + item.arg))
    if reg is None:
        raise ValueError(name)
    lines.append(f'GPU_MAGIC({reg:#06x}, {ast.literal_eval(item.value):#010x}) // {item.arg}\n')
text = ''.join(lines)
out = root / 'include/hakios-metal/a730-state.inc'
if '--check' in sys.argv:
    if out.read_text() != text:
        sys.exit('a730-state.inc is stale')
else:
    out.write_text(text)
print(f'{len(lines) - 1} A730 magic-register writes checked against Mesa')
