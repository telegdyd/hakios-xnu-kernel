#!/usr/bin/env python3
"""Generate the shared register-offset table from Mesa 25.0.7's a6xx.xml.

Usage: chip-registers.py path/to/a6xx.xml [--check]
Descriptor word indices (TEX_CONST/SAMP) are not MMIO registers. Field encoders
are deliberately separate: a valid offset does not imply compatible fields.
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]


def applies(variants, generation):
    if variants is None:
        return True
    for part in variants.split(','):
        ends = part.split('-')
        low = int(ends[0][1])
        high = int(ends[1][1]) if len(ends) > 1 and ends[1] else (99 if len(ends) > 1 else low)
        if low <= generation <= high:
            return True
    return False


def main():
    view = {6: {}, 7: {}}

    def signature(node, generation):
        # Separate A6xx/A7xx definitions can share a name and offset while
        # moving bits (SP_CS_CNTL_1.THREADSIZE: bit 9 -> bit 8).
        attrs = tuple(sorted((key, value) for key, value in node.attrib.items()
                             if key not in ('variants', 'offset', 'usage')))
        children = tuple(signature(child, generation) for child in node
                         if child.tag.split('}')[-1] != 'doc' and applies(child.get('variants'), generation))
        if node.get('type') in bitsets:
            children += (signature(bitsets[node.get('type')], generation),)
        return node.tag, attrs, children

    def walk(node, base=0, inherited=None, prefix=''):
        for item in node:
            tag = item.tag.split('}')[-1]
            variants = item.get('variants', inherited)
            if tag not in ('reg32', 'reg64', 'array', 'stripe'):
                continue
            if tag == 'stripe':
                walk(item, base, variants, prefix)
                continue
            offset = base + int(item.get('offset', '0'), 0)
            name = prefix + item.get('name', '')
            fields = any(child.get('variants') for child in item.iter() if child is not item)
            for gen in (6, 7):
                if applies(variants, gen):
                    view[gen][name] = (offset, fields, signature(item, gen))
            if tag == 'array':
                walk(item, offset, variants, name + '_')

    xml = ET.parse(sys.argv[1]).getroot()
    bitsets = {item.get('name'): item for item in xml.iter() if item.tag.endswith('bitset')}
    domain = next(item for item in xml if item.tag.endswith('domain') and item.get('name') == 'A6XX')
    walk(domain)
    source = (ROOT / 'include/hakios-metal/a6xx.hpp').read_text()
    rows = re.findall(r'constexpr uint32_t REG_A6XX_(\w+)\s*=\s*(0x[\da-fA-F]+)', source)
    output = ['// Generated by tools/chip-registers.py from Mesa 25.0.7 a6xx.xml.\n',
              '// GPU_REG(name, A6xx offset, A7xx offset, generation-specific fields)\n',
              '// 0xffffffff means absent; never write it to the GPU.\n']
    for name, old in rows:
        if name.startswith(('TEX_CONST_', 'TEX_SAMP_')):
            continue
        if name not in view[6] or view[6][name][0] != int(old, 16):
            raise ValueError(f'A6xx register disagrees with XML: {name}')
        new, fields, sig = view[7].get(name, (0xffffffff, False, None))
        fields = fields or (sig is not None and view[6][name][2] != sig)
        output.append(f'GPU_REG({name}, {int(old, 16):#06x}, {new:#06x}, {str(fields).lower()})\n')
    for name in ('HLSQ_CS_LAST_LOCAL_SIZE', 'SP_CS_UNKNOWN_A9BE', 'RB_CCU_CNTL2', 'SP_CS_VGPR_CONFIG'):
        new, fields, _ = view[7][name]
        output.append(f'GPU_REG({name}, 0xffffffff, {new:#06x}, {str(fields).lower()})\n')
    text = ''.join(output)
    target = ROOT / 'include/hakios-metal/chip-registers.inc'
    if '--check' in sys.argv:
        if target.read_text() != text:
            sys.exit('chip-registers.inc is stale')
    else:
        target.write_text(text)
    print(f'{len(output) - 3} register entries checked against Mesa XML')


if __name__ == '__main__':
    main()
