#!/usr/bin/env python3
"""hakios.gcc8450.h from Linux v6.12 drivers/clk/qcom/gcc-sm8450.c: each branch clock's name and halt register
(bit 31 CLK_OFF), and the ones Linux keeps on at probe (qcom_branch_set_clk_en). Usage: gen-gcc8450.py gcc-sm8450.c out.h"""
import re, sys
src = open(sys.argv[1]).read()
rows, seen = [], set()
for m in re.finditer(r'static struct clk_branch (\w+) = \{(.*?)\n\};', src, re.S):
    name, body = m.group(1), m.group(2)
    h = re.search(r'\.halt_reg = (0x[0-9a-f]+)', body)
    if not h or name.endswith('_hw_ctl_clk'):
        continue
    off = int(h.group(1), 16)
    if off in seen:
        continue
    seen.add(off)
    rows.append((off, name[4:] if name.startswith('gcc_') else name, 'BRANCH_HALT_VOTED' in body))
for m in re.finditer(r'qcom_branch_set_clk_en\(regmap, (0x[0-9a-f]+)\); /\* GCC_(\w+) \*/', src):
    off = int(m.group(1), 16)
    if off not in seen:
        seen.add(off); rows.append((off, m.group(2).lower() + ' (kept on)', False))
rows.sort()
with open(sys.argv[2], 'w', newline='\n') as f:
    f.write('/* generated by tools/gen-gcc8450.py from Linux v6.12 drivers/clk/qcom/gcc-sm8450.c: do not edit */\n')
    f.write('static const struct gcc_branch { uint32_t offset; const char *name; } gcc8450_branches[] = {\n')
    for off, name, voted in rows:
        f.write(f'\t{{ {off:#07x}, "{name}" }},\n')
    f.write('};\n')
print(len(rows), 'branches')
